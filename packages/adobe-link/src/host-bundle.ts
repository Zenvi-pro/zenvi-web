/**
 * The host script an Adobe app loads (manifest `ScriptPath`): every
 * `extension/host/common/*.jsx`, then a generated block (version, TASTE,
 * catalog titles), then every `extension/host/<app>/*.jsx`, each group in
 * file name order. The extension build writes this text to
 * `host/<app>.jsx`; the test harness runs the same text, so tests exercise
 * exactly what ships.
 */

import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { catalogFor } from "./catalog/index.js";
import type { HostId } from "./catalog/types.js";
import { TASTE } from "./taste.js";
import { LINK_VERSION } from "./version.js";

/** CEP host codes, used for script folders and bundle names. */
export type HostApp = "aeft" | "ppro";

export const HOST_APPS: readonly HostApp[] = ["aeft", "ppro"];

export const HOST_OF_APP: { readonly [A in HostApp]: HostId } = { aeft: "aftereffects", ppro: "premiere" };

export const APP_OF_HOST: { readonly [H in HostId]: HostApp } = { aftereffects: "aeft", premiere: "ppro" };

const APP_LABEL: { readonly [A in HostApp]: string } = { aeft: "After Effects", ppro: "Premiere Pro" };

/** packages/adobe-link */
export const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const HOST_SCRIPT_DIR = path.join(PACKAGE_ROOT, "extension", "host");

export interface HostSource {
  /** Relative to `extension/host`, POSIX separators (`common/10-zenvi.jsx`). */
  file: string;
  text: string;
}

/** A section of the bundle: which source a run of lines came from. */
export interface BundleSection {
  file: string;
  /** 1-based first line of the section's text in the bundle. */
  startLine: number;
  lineCount: number;
}

export interface HostBundle {
  app: HostApp;
  text: string;
  sections: BundleSection[];
}

export const GENERATED_SECTION = "(generated)";

function sourcesIn(dir: string, folder: string): HostSource[] {
  return readdirSync(path.join(dir, folder))
    .filter((name) => name.endsWith(".jsx"))
    .sort()
    .map((name) => ({ file: `${folder}/${name}`, text: readFileSync(path.join(dir, folder, name), "utf8") }));
}

/** The hand-written sources of an app's host script, in bundle order. */
export function hostSources(app: HostApp, dir: string = HOST_SCRIPT_DIR): HostSource[] {
  return [...sourcesIn(dir, "common"), ...sourcesIn(dir, app)];
}

/** JSON as an ES3 expression with every non-ASCII character escaped. */
export function asciiJson(value: unknown): string {
  return JSON.stringify(value).replace(/[\u0080-\uffff]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
}

/** Version, TASTE and the catalog facts dispatch needs (title, mutating) for one app. */
export function generatedBlock(app: HostApp): string {
  const catalog: Record<string, { title: string; mutating: boolean }> = {};
  for (const def of catalogFor(HOST_OF_APP[app])) {
    catalog[def.name] = { title: def.title, mutating: def.annotations.readOnlyHint !== true };
  }
  return [
    "// Generated by the Zenvi Link build from src/version.ts, src/taste.ts and src/catalog. Do not edit.",
    `ZenviLink.version = ${asciiJson(LINK_VERSION)};`,
    `ZenviLink.TASTE = ${asciiJson(TASTE)};`,
    `ZenviLink.CATALOG = ${asciiJson(catalog)};`,
    "",
  ].join("\n");
}

function lineCount(text: string): number {
  return text.split("\n").length;
}

/** The complete host script for an app. */
export function bundleHostScript(app: HostApp, dir: string = HOST_SCRIPT_DIR): HostBundle {
  const sources = hostSources(app, dir);
  const common = sources.filter((s) => s.file.startsWith("common/"));
  const own = sources.filter((s) => !s.file.startsWith("common/"));
  const parts: HostSource[] = [...common, { file: GENERATED_SECTION, text: generatedBlock(app) }, ...own];
  const header = `// Zenvi Link ${LINK_VERSION}: host script for ${APP_LABEL[app]}. Built from extension/host/{common,${app}}/*.jsx; do not edit.\n`;
  let text = header;
  let line = lineCount(header);
  const sections: BundleSection[] = [];
  for (const part of parts) {
    const marker = `// ---- ${part.file} ----\n`;
    const body = part.text.endsWith("\n") ? part.text : `${part.text}\n`;
    text += marker;
    line += 1;
    sections.push({ file: part.file, startLine: line, lineCount: lineCount(body) - 1 });
    text += body;
    line += lineCount(body) - 1;
  }
  return { app, text, sections };
}

/** Map a line of the bundle (ExtendScript `error.line`) back to its source file and line. */
export function locateBundleLine(bundle: HostBundle, line: number): { file: string; line: number } | undefined {
  for (const section of bundle.sections) {
    if (line >= section.startLine && line < section.startLine + section.lineCount) {
      return { file: section.file, line: line - section.startLine + 1 };
    }
  }
  return undefined;
}
