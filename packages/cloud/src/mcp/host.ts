/**
 * The ToolHost that engine catalog tools get on the remote MCP server, for
 * one call on one cloud project. Everything maps onto Zenvi Cloud storage;
 * nothing touches the server's own files beyond a per-call scratch folder:
 *
 *   media   probe project media (cached download) and media this call
 *           generated; import URLs (SSRF-guarded); writeGenerated stores bytes
 *           (title SVGs) as content-addressed project media;
 *   frames  preview frames through the cloud renderer;
 *   assets  the engine's bundled assets (title templates);
 *   audio   loudness envelopes of project media (remove_silence_tool);
 *   storage readText of project media, writeText to a downloadable export
 *           (export_captions_tool). Cloud projects save themselves, so
 *           save/open are refused;
 *   backend api.zenvi.pro as the person who allowed the connector (search,
 *           stock, catalog, TTS). AI video is a cloud job, not this host.
 */

import { mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { join } from "node:path";
import type { CloudMediaRef, HostCapability, Project, ToolHost } from "@zenvi/engine";
import { ApiError, tooLarge } from "../http/errors.js";
import { withSuffix } from "../projects/files.js";
import { displayName, fileSha256 } from "../projects/model.js";
import { filesByPath } from "../render/resolve.js";
import { attachmentDisposition, cleanFileName, normalizeContentType } from "../services/media.js";
import { exportPath } from "../services/paths.js";
import { sha256Hex } from "../util/crypto.js";
import type { Services } from "../container.js";
import type { McpCallContext } from "./types.js";

const GENERATED_MAX_BYTES = 20 * 1024 * 1024;
const TEXT_MAX_BYTES = 2 * 1024 * 1024;
const EXPORT_URL_SECONDS = 24 * 3600;

export interface CloudHost {
  host: ToolHost;
  /** Remove this call's scratch files. */
  dispose(): Promise<void>;
}

/** Host capabilities this build can offer (decides which catalog tools are listed). */
export function cloudCapabilities(services: Services): Set<HostCapability> {
  const caps = new Set<HostCapability>(["storage"]);
  if (services.prober.available) caps.add("media");
  if (services.frames.available) caps.add("frames");
  if (services.assets) caps.add("assets");
  if (services.analyzeAudio) caps.add("audio");
  if (services.backendSessions.enabled) caps.add("backend");
  return caps;
}

function baseName(path: string): string {
  return path.split(/[\\/]/).pop() || path;
}

/** A download name for an export: the base name, reduced to safe characters. */
function exportName(path: string, fallback: string): string {
  const cleaned = baseName(path)
    .replace(/[^A-Za-z0-9._-]+/g, "_")
    .replace(/^[^A-Za-z0-9]+/, "")
    .slice(0, 100);
  return cleaned || fallback;
}

export function createCloudHost(ctx: McpCallContext, projectId: string, project: () => Project): CloudHost {
  const { services } = ctx;
  const userId = ctx.principal.userId;
  /** Media this call generated: project path → scratch file + content address. */
  const generated = new Map<string, { file: string; cloud: CloudMediaRef }>();
  let scratch: Promise<string> | undefined;
  const scratchDir = (): Promise<string> => (scratch ??= mkdtemp(join(services.config.renderTmpDir, "zenvi-tool-")));

  /** A local copy of a path this project knows: generated by this call, or a cloud file in its bin. */
  const localCopy = async (path: string): Promise<string> => {
    const made = generated.get(path);
    if (made) return made.file;
    const file = filesByPath(project()).get(path);
    if (!file || !fileSha256(file)) {
      throw new ApiError(400, "invalid_request", `"${baseName(path)}" is not media in this project's Zenvi Cloud bin.`);
    }
    try {
      return await services.mediaCache.get(userId, file);
    } catch (error) {
      throw new ApiError(422, "media_missing", `"${displayName(file)}" could not be read from Zenvi Cloud (${error instanceof Error ? error.message : String(error)}).`);
    }
  };

  const host: ToolHost = { log: (message) => services.log.debug(message) };
  const caps = cloudCapabilities(services);

  if (caps.has("media")) {
    host.media = {
      probe: async (path) => {
        const info = await services.prober.probe(await localCopy(path));
        const made = generated.get(path);
        // `addFile` builds the bin entry from this info, so generated media get
        // their content address (`file.cloud`) just like imported media.
        return made ? { ...info, path, cloud: made.cloud } : { ...info, path };
      },
      writeGenerated: async (name, bytes, contentType) => {
        const type = normalizeContentType(contentType);
        if (!type) throw new ApiError(415, "unsupported_media_type", `Zenvi Cloud does not store ${contentType} files.`);
        if (bytes.byteLength > GENERATED_MAX_BYTES) throw tooLarge("The generated file is too large.");
        const sha256 = sha256Hex(bytes);
        const fileName = cleanFileName(name);
        await services.media.storeBytes(userId, { sha256, bytes, name: fileName, contentType: type });
        const file = join(await scratchDir(), `${sha256}-${fileName}`);
        await writeFile(file, bytes);
        // The desktop keeps titles in the project's assets folder (`@assets/title/…`).
        const folder = type === "image/svg+xml" ? "title" : "generated";
        let path = `@assets/${folder}/${fileName}`;
        if (project().files.some((f) => f.path === path && f.cloud?.sha256 !== sha256)) path = `@assets/${folder}/${withSuffix(fileName, sha256.slice(0, 8))}`;
        generated.set(path, { file, cloud: { sha256, size: bytes.byteLength, name: fileName, content_type: type } });
        return path;
      },
    };
    if (services.importer.available) {
      host.media.importUrl = (url, options) => services.importer.importUrl(userId, url, { filename: options?.filename, signal: options?.signal ?? ctx.signal });
    }
  }

  if (caps.has("frames")) {
    host.frames = {
      renderFrame: async (current, seconds, options) => {
        const preview = await services.frames.preview({
          userId,
          projectId,
          project: current,
          revision: sha256Hex(JSON.stringify(current)),
          seconds,
          width: options?.width,
          signal: ctx.signal,
        });
        return preview.image;
      },
    };
  }

  const assets = services.assets;
  if (assets) host.assets = { readText: (path) => assets.readText(path) };

  const analyze = services.analyzeAudio;
  if (analyze) {
    host.audio = {
      analyzeAudio: async (path, options) => analyze(await localCopy(path), { ...options, signal: options?.signal ?? ctx.signal }),
    };
  }

  if (caps.has("backend")) {
    host.backend = {
      baseUrl: services.config.backendUrl,
      request: (path, init) => services.backendSessions.request(userId, path, { ...init, signal: init?.signal ?? ctx.signal }),
    };
  }

  host.storage = {
    save: async () => {
      throw new ApiError(400, "unsupported", "Zenvi Cloud saves the project after every edit; there is no file to save it to.");
    },
    open: async () => {
      throw new ApiError(400, "unsupported", "Open cloud projects with open_project.");
    },
    readText: async (path) => {
      const local = await localCopy(path);
      if ((await stat(local)).size > TEXT_MAX_BYTES) throw tooLarge(`"${baseName(path)}" is too large to read as text.`);
      return readFile(local, "utf8");
    },
    writeText: async (path, text, contentType) => {
      const bytes = Buffer.byteLength(text, "utf8");
      if (bytes > TEXT_MAX_BYTES) throw tooLarge("The exported file is too large.");
      const name = exportName(path, "export.txt");
      const type = contentType ?? "text/plain";
      const blobPath = exportPath(userId, projectId, name);
      await services.media.assertFits(userId, bytes);
      await services.blobs.write(blobPath, text, { contentType: type, contentDisposition: attachmentDisposition(name) });
      services.media.invalidateUsage(userId);
      // The download link is the "location" the tool reports to the person.
      return services.blobs.signUrl(blobPath, {
        permission: "read",
        expiresInSeconds: EXPORT_URL_SECONDS,
        contentType: type,
        contentDisposition: attachmentDisposition(name),
      });
    },
  };

  return {
    host,
    async dispose() {
      if (scratch) await rm(await scratch, { recursive: true, force: true });
    },
  };
}
