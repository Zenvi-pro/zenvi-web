#!/usr/bin/env python3
"""Generate src/titles/animated-templates.data.ts from zenvi-core's Blender titles.

Dev-time only. Reads src/blender/*.xml at origin/develop (the 19 templates of
Title > Animated Title) the way zenvi-core's classes/blender_titles.py does
(`template_summary`, `animation_details`), so add_animated_title_tool takes the
same template names, parameters, defaults, ranges and choices as the desktop.

    python3 packages/engine/scripts/gen-animated-titles.py
"""

import json
import os
import subprocess
from xml.dom import minidom

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "titles", "animated-templates.data.ts")
REPO = os.environ.get("ZENVI_DESKTOP_REPO", os.path.expanduser("~/Projects/zenvi"))
REF = os.environ.get("ZENVI_DESKTOP_REF", "origin/develop")


def git(*args):
    return subprocess.check_output(["git", "-C", REPO, *args])


def text(doc, tag):
    nodes = doc.getElementsByTagName(tag)
    if nodes and nodes[0].childNodes:
        return nodes[0].childNodes[0].data
    return ""


def details(name, xml):
    doc = minidom.parseString(xml)
    out = {
        "name": name,
        "title": text(doc, "title"),
        "description": text(doc, "description"),
        "service": text(doc, "service"),
        "params": [],
    }
    for param in doc.getElementsByTagName("param"):
        item = {"default": ""}
        for att in ("title", "description", "name", "type"):
            if param.attributes.get(att) is not None:
                item[att] = param.attributes[att].value
        for tag in ("min", "max", "step", "digits", "default"):
            for p in param.getElementsByTagName(tag):
                if p.childNodes:
                    item[tag] = getattr(p.firstChild, "data", "")
        values = {}
        for p in param.getElementsByTagName("value"):
            if "name" in p.attributes and "num" in p.attributes:
                values[p.attributes["name"].value] = p.attributes["num"].value
        item["values"] = values
        out["params"].append(item)
    return out


def main():
    commit = git("rev-parse", "--short", REF).decode().strip()
    listing = git("ls-tree", "--name-only", REF, "src/blender/").decode().split("\n")
    names = sorted(os.path.basename(p) for p in listing if p.endswith(".xml"))
    templates = []
    for file in names:
        xml = git("show", f"{REF}:src/blender/{file}")
        templates.append(details(os.path.splitext(file)[0], xml))
    body = ",\n".join("  " + json.dumps(t, ensure_ascii=False) for t in templates)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(
            "// Generated by packages/engine/scripts/gen-animated-titles.py from zenvi-core\n"
            f"// src/blender/*.xml at {REF} ({commit}). Do not edit by hand.\n\n"
            "/** A template parameter as classes/blender_titles.py `animation_details` reads it (values are XML text). */\n"
            "export interface AnimatedTitleParamData {\n"
            "  name: string;\n"
            "  type: string;\n"
            "  title?: string;\n"
            "  description?: string;\n"
            "  default: string;\n"
            "  min?: string;\n"
            "  max?: string;\n"
            "  step?: string;\n"
            "  digits?: string;\n"
            "  /** Choice label -> value. */\n"
            "  values: Readonly<Record<string, string>>;\n"
            "}\n\n"
            "export interface AnimatedTitleData {\n"
            "  /** File name without .xml, e.g. \"fly_by_1\". */\n"
            "  name: string;\n"
            "  title: string;\n"
            "  description: string;\n"
            "  /** The .blend file, e.g. \"fly_by_1.blend\". */\n"
            "  service: string;\n"
            "  params: readonly AnimatedTitleParamData[];\n"
            "}\n\n"
            "/** Title > Animated Title's templates, sorted by file name. */\n"
            f"export const ANIMATED_TITLE_DATA: readonly AnimatedTitleData[] = [\n{body},\n];\n"
        )
    print(f"wrote {len(templates)} templates to {OUT}")


if __name__ == "__main__":
    main()
