#!/usr/bin/env python3
"""Regenerate src/ops/animation-presets.data.ts from zenvi-core src/animation_presets.py.

Dev-time only (reads origin/main through git):
    python3 packages/engine/scripts/gen-animation-presets.py
"""
import json
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.environ.get("ZENVI_DESKTOP_REPO", os.path.expanduser("~/Projects/zenvi"))
OUT = os.path.join(HERE, "..", "src", "ops", "animation-presets.data.ts")

source = subprocess.check_output(["git", "-C", REPO, "show", "origin/main:src/animation_presets.py"]).decode("utf-8")
commit = subprocess.check_output(["git", "-C", REPO, "rev-parse", "--short", "origin/main"]).decode().strip()
scope = {}
exec(compile(source, "animation_presets.py", "exec"), scope)
presets = {
    name: {prop: [list(point) for point in points] for prop, points in channels.items()}
    for name, channels in scope["PRESETS"].items()
}
easing = {name: list(values) for name, values in scope["KEYFRAME_EASING"].items()}
with open(OUT, "w") as f:
    f.write("// Generated by packages/engine/scripts/gen-animation-presets.py from zenvi-core\n")
    f.write(f"// src/animation_presets.py at origin/main ({commit}). Some keyframe data is derived\n")
    f.write("// from Animate.css v4.1.1 (MIT, Copyright (c) 2020 Daniel Eden). Do not edit by hand.\n\n")
    f.write("/** Point: [frame (1..31 at 30 fps), value, easing name?]. */\n")
    f.write("export type AnimationPoint = readonly [number, number, string?];\n\n")
    f.write("/** CSS cubic-bezier (x1, y1, x2, y2) per easing name. */\n")
    f.write(f"export const KEYFRAME_EASING: Readonly<Record<string, readonly [number, number, number, number]>> = {json.dumps(easing)};\n\n")
    f.write("/** Motion presets: property → points. */\n")
    f.write("export const ANIMATION_PRESET_DATA: Readonly<Record<string, Readonly<Record<string, readonly AnimationPoint[]>>>> = {\n")
    for name, channels in presets.items():
        f.write(f"  {json.dumps(name)}: {json.dumps(channels)},\n")
    f.write("};\n")
print(f"wrote {OUT} ({len(presets)} presets)")
