#!/usr/bin/env node
// Copy zenvi-core's emoji set (the Emojis dock's 1,239 OpenMoji SVGs,
// src/emojis/color/svg) into packages/engine/assets/emojis/, where projects
// find them as `@emojis/<file>`, and write assets/emojis/catalog.json: the
// file list plus the openmoji-optimized.json fields the dock and the emoji
// tools read. Dev-time only:
//   node packages/engine/scripts/gen-emojis.mjs
//
// The SVGs are minified without changing what they draw: element ids (the
// set references none), empty groups, comments and whitespace between tags
// and inside attribute values go; numbers are kept as written.
//
// OpenMoji (openmoji.org) graphics are CC BY-SA 4.0.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { DESKTOP_REF, desktopCommit, readText, readTree } from "./lib/desktop-git.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, "../assets/emojis");
const SOURCE = "src/emojis/color/svg/";
/** openmoji-optimized.json fields the catalog keeps (emoji_catalog.py `entry_for`). */
const FIELDS = ["emoji", "annotation", "group", "subgroups", "tags", "openmoji_tags", "skintone"];

function minify(svg, file) {
  if (/<text\b/.test(svg)) throw new Error(`${file}: has text; whitespace between tags would matter`);
  let out = svg.replace(/<!--[\s\S]*?-->/g, "");
  if (!/url\(#|href=/.test(out)) out = out.replace(/\s+id="[^"]*"/g, "");
  out = out.replace(/>\s+</g, "><");
  for (let prev = ""; prev !== out; ) {
    prev = out;
    out = out.replace(/<g\s*\/>|<g\s*><\/g>/g, "");
  }
  out = out.replace(/="([^"]*)"/g, (_m, value) => `="${value.replace(/\s+/g, " ").trim()}"`);
  out = out.replace(/\s+\/>/g, "/>");
  return `${out.trim()}\n`;
}

const files = [];
let before = 0;
let after = 0;
rmSync(assets, { recursive: true, force: true });
mkdirSync(assets, { recursive: true });
for (const [path, bytes] of readTree(SOURCE)) {
  const name = path.slice(SOURCE.length);
  if (name.includes("/") || !name.toLowerCase().endsWith(".svg") || name.startsWith(".")) continue;
  const svg = minify(bytes.toString("utf8"), name);
  writeFileSync(join(assets, name), svg);
  files.push(name);
  before += bytes.length;
  after += Buffer.byteLength(svg);
}
// emoji_model.py / emoji_catalog.py list the folder with sorted(os.listdir()): code-point order.
files.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

const optimized = JSON.parse(readText("src/emojis/data/openmoji-optimized.json"));
const metadata = {};
for (const file of files) {
  const code = file.replace(/\.svg$/i, "");
  const meta = optimized[code];
  if (!meta) continue;
  metadata[code] = Object.fromEntries(FIELDS.filter((key) => meta[key] !== undefined && meta[key] !== "").map((key) => [key, meta[key]]));
}

const catalog = {
  source: `zenvi-core src/emojis at ${DESKTOP_REF} (${desktopCommit()}); generated by packages/engine/scripts/gen-emojis.mjs`,
  license: "OpenMoji (https://openmoji.org) graphics: CC BY-SA 4.0",
  files,
  metadata,
};
writeFileSync(join(assets, "catalog.json"), `${JSON.stringify(catalog)}\n`);
console.log(
  `copied ${files.length} emojis to ${assets} (${(before / 1e6).toFixed(2)} MB -> ${(after / 1e6).toFixed(2)} MB); ` +
    `catalog.json ${(Buffer.byteLength(JSON.stringify(catalog)) / 1e3).toFixed(0)} kB`,
);
