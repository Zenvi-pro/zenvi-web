#!/usr/bin/env node
// Regenerate src/presets/export-presets.data.ts from zenvi-core's export
// presets (src/presets/*.xml, read by src/windows/export.py). Dev-time only:
//   node packages/engine/scripts/gen-export-presets.mjs
import { writeFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";
import { DESKTOP_REF, desktopCommit, readTree } from "./lib/desktop-git.mjs";

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" };
const decode = (text) => text.replace(/&(amp|lt|gt|quot|apos);/g, (_, name) => ENTITIES[name]);

/** Every `<tag …>text</tag>` (or `<tag …/>`) of one name: `{ attrs, text }`. */
function elements(xml, tag) {
  const out = [];
  const re = new RegExp(`<${tag}(\\s[^>]*?)?(?:/>|>([\\s\\S]*?)</${tag}>)`, "g");
  for (const m of xml.matchAll(re)) {
    const attrs = {};
    for (const a of (m[1] ?? "").matchAll(/([\w-]+)\s*=\s*"([^"]*)"/g)) attrs[a[1]] = decode(a[2]);
    out.push({ attrs, text: decode((m[2] ?? "").trim()) });
  }
  return out;
}

function one(xml, tag, file) {
  const found = elements(xml, tag);
  if (found.length !== 1) throw new Error(`${file}: expected one <${tag}>, found ${found.length}`);
  return found[0];
}

function int(text, file, tag) {
  const n = Number.parseInt(text, 10);
  if (!Number.isFinite(n)) throw new Error(`${file}: <${tag}> is not an integer`);
  return n;
}

const presets = [];
for (const [path, bytes] of readTree("src/presets/")) {
  const file = posix.basename(path);
  if (!file.endsWith(".xml")) continue;
  const xml = bytes.toString("utf8");
  const rates = (tag) => {
    const { attrs } = one(xml, tag, file);
    return { low: attrs.low ?? "", med: attrs.med ?? "", high: attrs.high ?? "" };
  };
  const exportTo = elements(xml, "export-to")[0]?.text ?? null;
  presets.push({
    id: file.slice(0, -".xml".length),
    type: one(xml, "type", file).text,
    title: one(xml, "title", file).text,
    exportTo,
    videoFormat: one(xml, "videoformat", file).text,
    videoCodec: one(xml, "videocodec", file).text,
    audioCodec: one(xml, "audiocodec", file).text,
    channels: int(one(xml, "audiochannels", file).text, file, "audiochannels"),
    channelLayout: int(one(xml, "audiochannellayout", file).text, file, "audiochannellayout"),
    sampleRate: int(one(xml, "samplerate", file).text, file, "samplerate"),
    videoBitrate: rates("videobitrate"),
    audioBitrate: rates("audiobitrate"),
    profiles: elements(xml, "projectprofile").map((p) => p.text),
  });
}
presets.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "../src/presets/export-presets.data.ts");
writeFileSync(
  target,
  `// Generated by packages/engine/scripts/gen-export-presets.mjs from zenvi-core\n` +
    `// src/presets/*.xml at ${DESKTOP_REF} (${desktopCommit()}). Do not edit by hand.\n` +
    `import type { ExportPreset } from "./catalog.js";\n\n` +
    `export const EXPORT_PRESET_TABLE: readonly ExportPreset[] = [\n${presets.map((p) => `  ${JSON.stringify(p)},`).join("\n")}\n];\n`,
);
console.log(`wrote ${presets.length} presets to ${target}`);
