#!/usr/bin/env python3
"""Generate the engine's libopenshot tables from the real library.

Dev-time only. Writes:
  src/model/libopenshot-defaults.data.ts  default Clip / Mask JSON + clip property metadata
  src/effects/registry.data.ts            every EffectInfo effect: metadata, default JSON,
                                          property metadata (PropertiesJSON)

Run with the libopenshot 1.0 Python bindings on the path:

    PYTHONPATH=~/zenvi-deps-1.0/python DYLD_LIBRARY_PATH=~/zenvi-deps-1.0/lib \
      ~/Projects/zenvi/.venv/bin/python packages/engine/scripts/gen-libopenshot-tables.py

If the bindings cannot be imported the script exits without touching the tables.
"""

import json
import os
import sys

try:
    import openshot
except Exception as exc:  # pragma: no cover - dev tool
    print(f"libopenshot bindings unavailable ({exc}); tables left unchanged", file=sys.stderr)
    sys.exit(0)

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")

# Keys libopenshot fills with per-instance values; the engine sets them itself.
INSTANCE_KEYS = {"id"}


def strip_instance(data):
    return {k: v for k, v in data.items() if k not in INSTANCE_KEYS}


def is_keyframe_like(value):
    """A Keyframe ({Points}) or a Color ({red, green, blue[, alpha]} keyframes)."""
    if not isinstance(value, dict):
        return False
    if "Points" in value:
        return True
    return all(isinstance(value.get(c), dict) and "Points" in value[c] for c in ("red", "green", "blue"))


def prop_meta(props, defaults):
    """Keep the stable parts of PropertiesJSON (drop per-frame state).

    `keyframe` means "stored as a keyframe" (the default JSON value is a
    Keyframe or Color). PropertiesJSON's own `keyframe` flag only says whether
    a point sits on the requested frame, so it is not used.
    """
    out = {}
    for key, p in props.items():
        if not isinstance(p, dict):
            continue
        meta = {
            "name": p.get("name", key),
            "type": p.get("type"),
            "min": p.get("min"),
            "max": p.get("max"),
            "keyframe": is_keyframe_like(defaults.get(key)),
            "readonly": bool(p.get("readonly", False)),
        }
        if p.get("memo") and key != "id":
            meta["memo"] = p["memo"]
        choices = p.get("choices") or []
        if choices:
            meta["choices"] = [{"name": c.get("name"), "value": c.get("value")} for c in choices]
        out[key] = meta
    return out


DEFAULT_LEFT = {"X": 0.5, "Y": 1.0}
DEFAULT_RIGHT = {"X": 0.5, "Y": 0.0}


def is_simple_keyframe(value):
    """`Keyframe(y).JsonValue()`: one BEZIER point at X=1 with default handles."""
    if not isinstance(value, dict) or set(value.keys()) != {"Points"}:
        return False
    points = value["Points"]
    if len(points) != 1:
        return False
    p = points[0]
    return (
        set(p.keys()) == {"co", "handle_left", "handle_right", "handle_type", "interpolation"}
        and p["co"].get("X") == 1.0
        and p["interpolation"] == 0
        and p["handle_type"] == 0
        and p["handle_left"] == DEFAULT_LEFT
        and p["handle_right"] == DEFAULT_RIGHT
    )


def compact(value):
    """Encode libopenshot JSON compactly; the engine expands it exactly.

    {"$kf": y}          one-point keyframe (Keyframe(y))
    {"$color": [r,g,b,a]} Color whose four channels are one-point keyframes
    """
    if is_simple_keyframe(value):
        return {"$kf": value["Points"][0]["co"]["Y"]}
    if isinstance(value, dict):
        channels = ("red", "green", "blue", "alpha")
        if set(value.keys()) == set(channels) and all(is_simple_keyframe(value[c]) for c in channels):
            return {"$color": [value[c]["Points"][0]["co"]["Y"] for c in channels]}
        return {k: compact(v) for k, v in value.items()}
    if isinstance(value, list):
        return [compact(v) for v in value]
    return value


def ts_json(value):
    return json.dumps(value, indent=None, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def ts_entries(values):
    return "[\n" + "".join(f"  {ts_json(v)},\n" for v in values) + "]"


def ts_record(record):
    return "{\n" + "".join(f"  {json.dumps(k)}: {ts_json(v)},\n" for k, v in sorted(record.items())) + "}"


def header(generator_note):
    return (
        "// Generated by packages/engine/scripts/gen-libopenshot-tables.py from libopenshot "
        f"{openshot.OPENSHOT_VERSION_FULL}.\n// {generator_note} Do not edit by hand.\n"
    )


def gen_defaults():
    clip = openshot.Clip()
    clip_json = strip_instance(json.loads(clip.Json()))
    clip_json.pop("reader", None)
    clip_props = prop_meta(json.loads(clip.PropertiesJSON(1)), clip_json)
    mask = openshot.Mask()
    mask_json = strip_instance(json.loads(mask.Json()))
    mask_props = prop_meta(json.loads(mask.PropertiesJSON(1)), mask_json)
    path = os.path.join(SRC, "model", "libopenshot-defaults.data.ts")
    with open(path, "w") as f:
        f.write(header("Default JSON as Clip::JsonValue() / Mask::JsonValue() write it."))
        f.write('import type { PropertyMeta } from "./properties.js";\n\n')
        f.write("// Keyframes are encoded compactly: {$kf: y} and {$color: [r, g, b, a]}; see model/compact.ts.\n\n")
        f.write("/** `openshot.Clip().Json()` without `id` and `reader`. */\n")
        f.write(f"export const LIBOPENSHOT_CLIP_JSON: Readonly<Record<string, unknown>> = {ts_record(compact(clip_json))};\n\n")
        f.write("/** `openshot.Clip().PropertiesJSON(1)` metadata (types, ranges, choices). */\n")
        f.write(f"export const LIBOPENSHOT_CLIP_PROPERTIES: Readonly<Record<string, PropertyMeta>> = {ts_record(clip_props)};\n\n")
        f.write("/** `openshot.Mask().Json()` without `id`. */\n")
        f.write(f"export const LIBOPENSHOT_MASK_JSON: Readonly<Record<string, unknown>> = {ts_record(compact(mask_json))};\n\n")
        f.write("/** `openshot.Mask().PropertiesJSON(1)` metadata. */\n")
        f.write(f"export const LIBOPENSHOT_MASK_PROPERTIES: Readonly<Record<string, PropertyMeta>> = {ts_record(mask_props)};\n")
    print(f"wrote {path}")


def gen_effects():
    info = json.loads(openshot.EffectInfo().Json())
    effects = []
    for entry in info:
        name = entry["class_name"]
        effect = openshot.EffectInfo().CreateEffect(name)
        if effect is None:
            print(f"skip {name}: CreateEffect returned None", file=sys.stderr)
            continue
        raw = json.loads(effect.Json())
        # Tracked-object keys embed the effect id ("<id>-0"); keep a placeholder.
        defaults = strip_instance(json.loads(json.dumps(raw).replace(raw["id"], "{{id}}")))
        try:
            props = prop_meta(json.loads(effect.PropertiesJSON(1)), raw)
        except Exception as exc:  # some effects need a parent clip
            print(f"{name}: PropertiesJSON failed ({exc})", file=sys.stderr)
            props = {}
        effects.append({"info": entry, "defaults": compact(defaults), "properties": props})
    path = os.path.join(SRC, "effects", "registry.data.ts")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(header("One entry per EffectInfo effect."))
        f.write('import type { LibopenshotEffectEntry } from "./types.js";\n\n')
        f.write("// Keyframes are encoded compactly: {$kf: y} and {$color: [r, g, b, a]}; see model/compact.ts.\n\n")
        f.write(f"export const LIBOPENSHOT_EFFECTS: readonly LibopenshotEffectEntry[] = {ts_entries(effects)};\n")
    print(f"wrote {path} ({len(effects)} effects)")


if __name__ == "__main__":
    gen_defaults()
    gen_effects()
