#!/usr/bin/env python3
"""Regenerate src/ops/look-presets.data.ts from zenvi-core (the contract ref,
develop 1f80cb3d0): classes/film_grain_presets.py and the LOOK_EFFECT_PRESETS
table in classes/look_presets.py; plus src/ops/__fixtures__/color-grade-presets.json,
the output of classes/color_presets.py (every preset and the neutral grade)
that ops/look.ts (a code port) is tested against.

Dev-time only:  python3 packages/engine/scripts/gen-look-presets.py
Env: ZENVI_DESKTOP_REPO (default ~/Projects/zenvi), ZENVI_CONTRACT_REF (default 1f80cb3d0).
"""
import ast
import json
import os
import subprocess
import sys
import types

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.environ.get("ZENVI_DESKTOP_REPO", os.path.expanduser("~/Projects/zenvi"))
OUT = os.path.join(HERE, "..", "src", "ops", "look-presets.data.ts")
REF = os.environ.get("ZENVI_CONTRACT_REF", "1f80cb3d0")


def show(path):
    return subprocess.check_output(["git", "-C", REPO, "show", f"{REF}:{path}"]).decode("utf-8")


# The preset modules only need two openshot enum values.
sys.modules["openshot"] = types.SimpleNamespace(LINEAR=1, AUTO=0, BEZIER=0, CONSTANT=2)


def load(path):
    scope = {}
    exec(compile(show(path), path, "exec"), scope)
    return scope


color = load("src/classes/color_presets.py")
grain = load("src/classes/film_grain_presets.py")

color_names = [color[k] for k in (
    "COLOR_PRESET_AUTO_CONTRAST", "COLOR_PRESET_LIFT_SHADOWS", "COLOR_PRESET_WARM_UP", "COLOR_PRESET_SUNNY",
    "COLOR_PRESET_GLOOMY", "COLOR_PRESET_BOOST_COLOR")]
color_payloads = {name: color["apply_color_grade_preset"]({}, name) for name in color_names}
color_payloads["neutral"] = color["neutral_color_grade"]({})

grain_names = [grain[k] for k in (
    "FILM_GRAIN_PRESET_35MM_FINE", "FILM_GRAIN_PRESET_35MM_CLASSIC", "FILM_GRAIN_PRESET_35MM_GRITTY",
    "FILM_GRAIN_PRESET_16MM_CLASSIC", "FILM_GRAIN_PRESET_SUPER_8", "FILM_GRAIN_PRESET_HIGH_ISO")]
grain_values = {}
for name in grain_names:
    payload = grain["apply_film_grain_preset"]({"seed": 0}, name)
    grain_values[name] = {k: v["Points"][0]["co"]["Y"] for k, v in payload.items() if isinstance(v, dict) and "Points" in v}

# LOOK_EFFECT_PRESETS is a plain literal in look_presets.py.
tree = ast.parse(show("src/classes/look_presets.py"))
look = None
for node in tree.body:
    if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "LOOK_EFFECT_PRESETS" for t in node.targets):
        look = ast.literal_eval(node.value)
if look is None:
    raise SystemExit("LOOK_EFFECT_PRESETS not found")

commit = subprocess.check_output(["git", "-C", REPO, "rev-parse", "--short", REF]).decode().strip()
with open(OUT, "w") as f:
    f.write("// Generated by packages/engine/scripts/gen-look-presets.py from zenvi-core develop\n")
    f.write(f"// ({commit}): classes/film_grain_presets.py and\n")
    f.write("// classes/look_presets.py LOOK_EFFECT_PRESETS. Do not edit by hand.\n\n")
    f.write("/** Film Grain preset values (film_grain_presets.py, after `_base_values`). */\n")
    f.write("export const FILM_GRAIN_PRESETS: Readonly<Record<string, Readonly<Record<string, number>>>> = {\n")
    for name, values in grain_values.items():
        f.write(f"  {json.dumps(name)}: {json.dumps(values)},\n")
    f.write("};\n\n")
    f.write("/** Look ▸ effect presets by libopenshot class (look_presets.py LOOK_EFFECT_PRESETS). */\n")
    f.write("export const LOOK_EFFECT_PRESETS: Readonly<Record<string, Readonly<Record<string, Readonly<Record<string, number | string>>>>>> = {\n")
    for cls, presets in look.items():
        f.write(f"  {json.dumps(cls)}: {json.dumps(presets)},\n")
    f.write("};\n")
fixture = os.path.join(HERE, "..", "src", "ops", "__fixtures__", "color-grade-presets.json")
os.makedirs(os.path.dirname(fixture), exist_ok=True)
with open(fixture, "w") as f:
    json.dump(color_payloads, f, separators=(",", ":"), sort_keys=True)
    f.write("\n")
print(f"wrote {OUT} and {fixture}")
