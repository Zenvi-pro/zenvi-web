#!/usr/bin/env node
// Regenerate src/model/profiles.data.ts from zenvi-core's src/profiles/*.
// Dev-time only:  node packages/engine/scripts/gen-profiles.mjs
import { writeFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";
import { DESKTOP_REF, desktopCommit, readTree } from "./lib/desktop-git.mjs";

function parseProfile(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*([A-Za-z_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

const profiles = [];
for (const [path, bytes] of readTree("src/profiles/")) {
  const rel = path.slice("src/profiles/".length);
  const dir = posix.dirname(rel);
  if (dir !== "." && dir !== "legacy") continue;
  const key = posix.basename(rel);
  if (key.includes(".")) continue;
  const p = parseProfile(bytes.toString("utf8"));
  const int = (k) => Number.parseInt(p[k], 10);
  const entry = {
    key,
    description: p.description,
    width: int("width"),
    height: int("height"),
    fps: { num: int("frame_rate_num"), den: int("frame_rate_den") },
    progressive: p.progressive === "1",
    pixel_ratio: { num: int("sample_aspect_num"), den: int("sample_aspect_den") },
    display_ratio: { num: int("display_aspect_num"), den: int("display_aspect_den") },
  };
  if (p.colorspace) entry.colorspace = int("colorspace");
  if (p.spherical === "1") entry.spherical = true;
  if (dir === "legacy") entry.legacy = true;
  for (const [k, v] of Object.entries(entry)) {
    if (typeof v === "number" && !Number.isFinite(v)) throw new Error(`${rel}: bad ${k}`);
  }
  if (!entry.description) throw new Error(`${rel}: no description`);
  profiles.push(entry);
}
profiles.sort((a, b) => Number(a.legacy ?? false) - Number(b.legacy ?? false) || a.key.localeCompare(b.key));

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "../src/model/profiles.data.ts");
const body = profiles.map((p) => `  ${JSON.stringify(p)},`).join("\n");
writeFileSync(
  target,
  `// Generated by packages/engine/scripts/gen-profiles.mjs from zenvi-core\n` +
    `// src/profiles/ at ${DESKTOP_REF} (${desktopCommit()}). Do not edit by hand.\n` +
    `import type { Profile } from "./profiles.js";\n\n` +
    `export const PROFILE_TABLE: readonly Profile[] = [\n${body}\n];\n`,
);
console.log(`wrote ${profiles.length} profiles to ${target}`);
