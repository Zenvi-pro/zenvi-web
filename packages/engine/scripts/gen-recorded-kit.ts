/**
 * Generate packages/engine/src/sfx/recorded-kit.data.ts, the recorded SFX
 * kit's list (sfx/recorded.ts), from a curated JSON list of Freesound
 * sounds (sound-library/curate-kit.ts writes it): one object per sound with
 * group, id, name, username, tags, license_url, license_checked_at,
 * duration, preview_url, samplerate, sha256 and bytes (the preview file's)
 * and its measurement (sfx/analyse.ts, made from that preview).
 *
 *   npx tsx packages/engine/scripts/gen-recorded-kit.ts curated.json
 *   FREESOUND_API_KEY=... npx tsx packages/engine/scripts/gen-recorded-kit.ts curated.json --verify
 *
 * Refuses any sound that is not CC0 or whose preview is not on Freesound's
 * CDN. --verify asks Freesound for every id's licence again (the API key is
 * read from the environment, never written) and downloads every preview to
 * check its checksum.
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { KitAnalysis } from "../src/sfx/analyse.js";
import { RECORDED_GROUPS, type RecordedGroup, type RecordedSample } from "../src/sfx/recorded.js";

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/sfx/recorded-kit.data.ts");
const CC0 = /^https?:\/\/creativecommons\.org\/publicdomain\/zero\/1\.0\/?$/;
const CDN = /^https:\/\/cdn\.freesound\.org\/previews\/\d+\/\d+_\d+-hq\.mp3$/;

interface Curated {
  group: string;
  id: number;
  name: string;
  username: string;
  license_url: string;
  duration: number;
  preview_url: string;
  sha256: string;
  bytes: number;
  tags: string[];
  license_checked_at: string;
  samplerate: number;
  analysis: KitAnalysis;
}

/** Loudest 400 ms of every kit sound after its gain, LUFS: a common level to place and search from. */
const REFERENCE_LUFS = -18;
const CEILING_DBTP = -1;
const r1 = (x: number): number => Math.round(x * 10) / 10;
const r3 = (x: number): number => Math.round(x * 1000) / 1000;

function read(file: string): RecordedSample[] {
  const rows = JSON.parse(readFileSync(file, "utf8")) as Curated[];
  const seen = new Set<number>();
  return rows.map((r) => {
    if (!RECORDED_GROUPS.includes(r.group as RecordedGroup)) throw new Error(`${r.id}: unknown group ${r.group}`);
    if (!CC0.test(r.license_url)) throw new Error(`${r.id}: not CC0 (${r.license_url})`);
    if (!CDN.test(r.preview_url)) throw new Error(`${r.id}: preview not on cdn.freesound.org (${r.preview_url})`);
    if (!/^[0-9a-f]{64}$/.test(r.sha256)) throw new Error(`${r.id}: bad sha256`);
    if (seen.has(r.id)) throw new Error(`${r.id}: listed twice`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(r.license_checked_at)) throw new Error(`${r.id}: no licence check date`);
    seen.add(r.id);
    const a = r.analysis;
    return {
      group: r.group as RecordedGroup,
      id: r.id,
      name: r.name.slice(0, 120),
      username: r.username,
      duration: Math.round(r.duration * 1000) / 1000,
      url: r.preview_url,
      sha256: r.sha256,
      bytes: r.bytes,
      license: "CC0",
      licenseCheckedAt: r.license_checked_at,
      tags: r.tags.slice(0, 12),
      onsetMs: Math.round(a.onsetMs),
      peakMs: Math.round(a.peakMs),
      endMs: Math.round(a.endMs),
      attackMs: Math.round(a.attackMs),
      lufs: r1(a.lufs),
      truePeakDb: r1(a.truePeakDb),
      gainDb: r1(Math.min(REFERENCE_LUFS - a.lufsMax, CEILING_DBTP - a.truePeakDb)),
      crestDb: r1(a.crestDb),
      centroidHz: Math.round(a.centroidHz),
      lowShare: r3(a.lowShare),
      stereo: a.sideDb > -30,
      sourceRate: r.samplerate,
    };
  });
}

async function verify(samples: readonly RecordedSample[]): Promise<void> {
  const key = process.env.FREESOUND_API_KEY;
  if (!key) throw new Error("--verify needs FREESOUND_API_KEY in the environment");
  for (const s of samples) {
    const meta = (await (await fetch(`https://freesound.org/apiv2/sounds/${s.id}/?fields=id,license&token=${key}`)).json()) as { license?: string };
    if (!CC0.test(meta.license ?? "")) throw new Error(`${s.id}: Freesound now says ${meta.license}`);
    const bytes = new Uint8Array(await (await fetch(s.url)).arrayBuffer());
    const sha = createHash("sha256").update(bytes).digest("hex");
    if (sha !== s.sha256) throw new Error(`${s.id}: preview checksum changed (${sha})`);
    await new Promise((r) => setTimeout(r, 1100));
  }
}

const [file, flag] = process.argv.slice(2);
if (!file) throw new Error("usage: gen-recorded-kit.ts curated.json [--verify]");
const samples = read(file).sort((a, b) => RECORDED_GROUPS.indexOf(a.group) - RECORDED_GROUPS.indexOf(b.group) || a.id - b.id);
if (flag === "--verify") await verify(samples);
const lines = samples.map((s) => `  ${JSON.stringify(s)},`);
writeFileSync(
  OUT,
  `// Generated by packages/engine/scripts/gen-recorded-kit.ts from a curated Freesound list; do not edit by hand.\n` +
    `// Every sound is CC0 1.0 (checked per id); the audio is fetched on first use, never committed.\n\n` +
    `import type { RecordedSample } from "./recorded.js";\n\n` +
    `export const RECORDED_KIT: readonly RecordedSample[] = [\n${lines.join("\n")}\n];\n`,
);
console.log(`${samples.length} sounds -> ${path.relative(process.cwd(), OUT)}`);
