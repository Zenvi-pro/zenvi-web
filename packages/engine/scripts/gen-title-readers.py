DEFAULT_SENTINEL = "<default font>"
METHODS = ["detect_font", "update_font_color_button", "get_ref_color", "update_background_color_button", "best_contrast"]


class FontRecorder:
    """Stands in for QFont: records what detect_font sets."""

    Bold = 75
    Normal = 50

    def __init__(self, family=None):
        if isinstance(family, FontRecorder):
            self.__dict__.update(family.__dict__)
            return
        self.family = family
        self.italic = False
        self.weight = FontRecorder.Normal
        self.pixel_size = None
        self.point_size = None

    def exactMatch(self):
        return True

    def setItalic(self, value):
        self.italic = bool(value)

    def setWeight(self, value):
        self.weight = value

    def setPixelSize(self, value):
        if value > 0:  # Qt ignores (and warns about) sizes <= 0.
            self.pixel_size = value

    def setPointSizeF(self, value):
        if value > 0:
            self.point_size = value


class Button:
    def __init__(self):
        self.style = None

    def setStyleSheet(self, style):
        self.style = style


def load_methods():
    source = show("src/windows/title_editor.py")
    style_tools = types.ModuleType("style_tools")
    exec(compile(show("src/classes/style_tools.py").replace("from classes.logger import log", "log = None"), "style_tools.py", "exec"), style_tools.__dict__)
    module = ast.parse(source)
    editor = next(n for n in module.body if isinstance(n, ast.ClassDef) and n.name == "TitleEditor")
    namespace = {
        "QColor": QColor,
        "QFont": FontRecorder,
        "Qt": Qt,
        "style_to_dict": style_tools.style_to_dict,
        "log": types.SimpleNamespace(debug=lambda *a, **k: None, info=lambda *a, **k: None),
    }
    found = {}
    for node in editor.body:
        if isinstance(node, ast.FunctionDef) and node.name in METHODS:
            node.decorator_list = []
            code = compile(ast.Module(body=[node], type_ignores=[]), "title_editor.py", "exec")
            exec(code, namespace)
            found[node.name] = namespace[node.name]
    missing = set(METHODS) - set(found)
    if missing:
        raise SystemExit(f"title_editor.py is missing {sorted(missing)}")
    return found


def read_template(methods, svg):
    m = methods
    editor = types.SimpleNamespace()
    editor.xmldoc = minidom.parseString(svg.encode("utf-8"))
    editor.tspan_nodes = editor.xmldoc.getElementsByTagName("tspan")
    editor.text_nodes = editor.xmldoc.getElementsByTagName("text")
    editor.rect_node = editor.xmldoc.getElementsByTagName("rect")
    # A sentinel family: detect_font's fallback (no font in the template) is
    # QFont(get_font(default_font_family)), recorded as "not detected".
    editor.default_font_family = DEFAULT_SENTINEL
    editor.get_font = lambda name: name
    editor.best_contrast = m["best_contrast"]
    editor.get_ref_color = lambda ref_id: m["get_ref_color"](editor, ref_id)
    editor.btnFontColor = Button()
    editor.btnBackgroundColor = Button()
    # The editor's initial values (__init__): black background, white text.
    editor.bg_color_code = QColor(Qt.black)
    editor.font_color_code = QColor(Qt.white)
    # None so a template without a font falls to detect_font's default branch.
    editor.qfont = None

    out = {}
    try:
        m["detect_font"](editor)
        f = editor.qfont
        detected = f.family != DEFAULT_SENTINEL
        out["font"] = {
            "family": f.family,
            "italic": f.italic,
            "bold": f.weight == FontRecorder.Bold,
            "pixelSize": f.pixel_size,
            "pointSize": f.point_size,
        } if detected else None
    except Exception as ex:  # noqa: BLE001 - the fixture records desktop crashes
        out["font"] = {"error": type(ex).__name__}
    try:
        m["update_font_color_button"](editor)
        out["text"] = {"color": editor.font_color_code.name(), "alphaF": editor.font_color_code.alphaF(), "button": editor.btnFontColor.style}
    except Exception as ex:  # noqa: BLE001
        out["text"] = {"error": type(ex).__name__}
    try:
        m["update_background_color_button"](editor)
        out["background"] = (
            {"color": editor.bg_color_code.name(), "alphaF": editor.bg_color_code.alphaF(), "button": editor.btnBackgroundColor.style}
            if editor.rect_node else None
        )
    except Exception as ex:  # noqa: BLE001
        out["background"] = {"error": type(ex).__name__}
    return out


