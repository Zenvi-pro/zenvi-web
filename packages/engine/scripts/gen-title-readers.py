def main():
    count = write_color_table()
    with open(os.path.join(SRC, "model", "__fixtures__", "qcolor-names.json"), "w") as f:
        json.dump({"generator": "packages/engine/scripts/gen-title-readers.py", "cases": qcolor_cases()}, f, indent=1)
        f.write("\n")

    methods = load_methods()
    templates = []
    for name in sorted(n for n in ls("src/titles/") if n.endswith(".svg")):
        svg = show(f"src/titles/{name}")
        templates.append({"name": name, "sha256": hashlib.sha256(svg.encode("utf-8")).hexdigest(), **read_template(methods, svg)})
    synthetic = [{"name": key, "svg": svg, **read_template(methods, svg)} for key, svg in SYNTHETIC.items()]
    with open(os.path.join(SRC, "titles", "__fixtures__", "title-readers.json"), "w") as f:
        json.dump({"generator": "packages/engine/scripts/gen-title-readers.py", "templates": templates, "synthetic": synthetic}, f, indent=1)
        f.write("\n")
    print(f"{count} named colors, {len(COLOR_STRINGS)} color strings, {len(templates)} templates, {len(synthetic)} synthetic SVGs")


if __name__ == "__main__":
    main()
