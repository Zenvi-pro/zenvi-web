def show(path):
    return subprocess.check_output(["git", "-C", REPO, "show", f"origin/main:{path}"]).decode("utf-8")


def ls(path):
    out = subprocess.check_output(["git", "-C", REPO, "ls-tree", "--name-only", f"origin/main:{path}"])
    return out.decode("utf-8").split()


