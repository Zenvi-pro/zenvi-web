#!/usr/bin/env python3
"""Ground truth for the title editor's readers and Qt color-name parsing.

Dev-time only. Needs PyQt5 (the desktop venv has it):

    ~/Projects/zenvi/.venv/bin/python packages/engine/scripts/gen-title-readers.py

Writes
  - src/model/qcolor.data.ts: Qt 5.15's SVG color keyword table
    (`QColor.colorNames()` and their values);
  - src/model/__fixtures__/qcolor-names.json: `QColor(s).isValid()` / `.name()`
    / `.getRgbF()` for strings covering every parsing branch;
  - src/titles/__fixtures__/title-readers.json: what zenvi-core
    src/windows/title_editor.py `detect_font`, `update_font_color_button`
    (with `get_ref_color`) and `update_background_color_button` read from
    every desktop title template plus edge-case SVGs. The methods run
    unmodified (extracted from the source at origin/main) against real
    QColor and xml.dom.minidom; QFont is a recorder whose `exactMatch()` is
    true, so the result is the font the template asks for.
"""

