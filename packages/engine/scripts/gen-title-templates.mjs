#!/usr/bin/env node
// Copy zenvi-core's SVG title templates (src/titles/*.svg) into
// packages/engine/assets/titles/ unchanged and regenerate
// src/titles/templates.data.ts. Dev-time only:
//   node packages/engine/scripts/gen-title-templates.mjs
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";
import { DESKTOP_REF, desktopCommit, readTree } from "./lib/desktop-git.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, "../assets/titles");
const target = join(here, "../src/titles/templates.data.ts");

const files = [];
rmSync(assets, { recursive: true, force: true });
mkdirSync(assets, { recursive: true });
for (const [path, bytes] of readTree("src/titles/")) {
  const rel = path.slice("src/titles/".length);
  // titles_model.py: only top-level .svg files; skip hidden files and temp.svg.
  if (rel.includes("/") || !rel.toLowerCase().endsWith(".svg")) continue;
  if (rel.startsWith(".") || rel.toLowerCase() === "temp.svg") continue;
  writeFileSync(join(assets, rel), bytes);
  files.push(rel);
}
// Python sorted(): code-point order.
files.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

writeFileSync(
  target,
  `// Generated by packages/engine/scripts/gen-title-templates.mjs from zenvi-core\n` +
    `// src/titles/ at ${DESKTOP_REF} (${desktopCommit()}). Do not edit by hand.\n\n` +
    `/** Template file names, sorted like the desktop's titles list. */\n` +
    `export const TITLE_TEMPLATE_FILES: readonly string[] = [\n${files.map((f) => `  ${JSON.stringify(f)},`).join("\n")}\n];\n`,
);
console.log(`copied ${files.length} templates to ${posix.normalize(assets)}; wrote ${target}`);
