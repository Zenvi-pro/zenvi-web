#!/usr/bin/env python3
"""Bundle zenvi-core's transition masks and generate the catalog table.

Dev-time only. Reads src/transitions/{common,extra} at origin/main
(412 files: 7 SVG + 405 JPG) and

- records `openshot.QtImageReader(path).Json()` for every ORIGINAL mask, so
  the engine writes the same transition `reader` JSON as the desktop;
- copies the SVGs to packages/engine/assets/transitions/common/ unchanged;
- re-encodes the JPGs into packages/engine/assets/transitions/extra/ at most
  512 px on the long side, grayscale, `-q:v 3` (the originals total 45.6 MB;
  libopenshot scales a mask to the frame anyway, and every mask is neutral
  gray, so only resolution is lost);
- writes src/transitions/catalog.data.ts.

    PYTHONPATH=~/zenvi-deps-1.0/python DYLD_LIBRARY_PATH=~/zenvi-deps-1.0/lib \
      ~/Projects/zenvi/.venv/bin/python packages/engine/scripts/gen-transitions.py
"""

import io
import json
import math
import os
import shutil
import subprocess
import tarfile
import tempfile

import openshot

HERE = os.path.dirname(os.path.abspath(__file__))
ENGINE = os.path.join(HERE, "..")
ASSETS = os.path.join(ENGINE, "assets", "transitions")
OUT = os.path.join(ENGINE, "src", "transitions", "catalog.data.ts")
REPO = os.environ.get("ZENVI_DESKTOP_REPO", os.path.expanduser("~/Projects/zenvi"))
REF = os.environ.get("ZENVI_DESKTOP_REF", "origin/main")
CATEGORIES = ("common", "extra")
MAX_SIZE = 512
# Per-file fields of the reader JSON; everything else is the same for every mask.
VARYING = ("path", "width", "height", "file_size", "display_ratio")


def git(*args):
    return subprocess.check_output(["git", "-C", REPO, *args])


def extract(tmp):
    archive = git("archive", REF, "src/transitions")
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        tar.extractall(tmp, filter="data")
    return os.path.join(tmp, "src", "transitions")


def downscale(src, dst):
    subprocess.check_call([
        "ffmpeg", "-v", "error", "-y", "-i", src,
        "-vf", f"scale=w='min({MAX_SIZE},iw)':h='min({MAX_SIZE},ih)':force_original_aspect_ratio=decrease,format=gray",
        "-q:v", "3", dst,
    ])


def main():
    commit = git("rev-parse", "--short", REF).decode().strip()
    tmp = tempfile.mkdtemp(prefix="zenvi-transitions-")
    try:
        root = extract(tmp)
        shutil.rmtree(ASSETS, ignore_errors=True)
        rows = []
        template = None
        for category in CATEGORIES:
            os.makedirs(os.path.join(ASSETS, category))
            for name in sorted(os.listdir(os.path.join(root, category))):
                # transition_model.py skips hidden files and thumbs.db.
                if name.startswith(".") or "thumbs.db" in name.lower():
                    continue
                src = os.path.join(root, category, name)
                reader = json.loads(openshot.QtImageReader(src).Json())
                rest = {k: v for k, v in reader.items() if k not in VARYING}
                if template is None:
                    template = rest
                assert rest == template, f"{name}: reader fields differ from the template"
                w, h = reader["width"], reader["height"]
                g = math.gcd(w, h)
                assert reader["display_ratio"] == {"num": w // g, "den": h // g}, f"{name}: display_ratio"
                rows.append((category, name, w, h, reader["file_size"]))
                dst = os.path.join(ASSETS, category, name)
                if name.lower().endswith(".svg"):
                    shutil.copyfile(src, dst)
                else:
                    downscale(src, dst)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    body = "\n".join(f"  {json.dumps(list(r))}," for r in rows)
    with open(OUT, "w") as fh:
        fh.write(
            "// Generated by packages/engine/scripts/gen-transitions.py from zenvi-core\n"
            f"// src/transitions at {REF} ({commit}) and libopenshot {openshot.OPENSHOT_VERSION_FULL}.\n"
            "// Do not edit by hand.\n\n"
            "/** `QtImageReader(path).Json()` of a mask, without the per-file fields. */\n"
            f"export const MASK_READER_TEMPLATE = {json.dumps(template, sort_keys=True)} as const;\n\n"
            "/** Bundled JPG masks are re-encoded at most this many pixels on the long side. */\n"
            f"export const BUNDLED_MASK_MAX_SIZE = {MAX_SIZE};\n\n"
            "/** `[category, file, width, height, file_size]` of each original mask, as QtImageReader reports it. */\n"
            'export const TRANSITION_FILES: readonly (readonly ["common" | "extra", string, number, number, number])[] = [\n'
            f"{body}\n];\n"
        )
    print(f"wrote {len(rows)} transitions to {OUT}")


if __name__ == "__main__":
    main()
