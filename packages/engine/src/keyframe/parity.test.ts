/**
 * Parity with libopenshot 1.0: the fixture holds values sampled from the real
 * library through its Python bindings (scripts/gen-keyframe-fixture.py).
 */
import { describe, expect, it } from "vitest";
import fixture from "./__fixtures__/libopenshot-keyframes.json";
import { Interpolation, type ColorKeyframe, type Keyframe } from "../model/types.js";
import { compileKeyframe, evaluate, getInt, getLong, getDelta, getLength, getCount, isIncreasing } from "./evaluate.js";
import { pointToJson, resolvePoints, type KeyframeLike } from "./points.js";
import { openshotKeyframe, openshotPoint } from "./edit.js";
import { colorHexAt, constantColor, evaluateColor } from "./color.js";

interface Sample {
  frame: number;
  value: number;
  int: number;
  long: number;
  delta: number;
  increasing: boolean;
}

interface Case {
  name: string;
  keyframe: KeyframeLike;
  length: number;
  count: number;
  normalized: Keyframe;
  samples: Sample[];
}

const cases = fixture.keyframes as unknown as Case[];

describe("keyframe parity with libopenshot 1.0", () => {
  it("fixture was generated by libopenshot 1.0", () => {
    expect(fixture.libopenshot).toMatch(/^1\.0/);
    expect(cases.length).toBeGreaterThan(20);
  });

  for (const c of cases) {
    it(`${c.name}: GetValue/GetInt/GetLong/GetDelta/IsIncreasing match`, () => {
      const compiled = compileKeyframe(c.keyframe);
      expect(getLength(c.keyframe)).toBe(c.length);
      expect(getCount(c.keyframe)).toBe(c.count);
      for (const s of c.samples) {
        const at = `${c.name} frame ${s.frame}`;
        expect(evaluate(c.keyframe, s.frame), at).toBe(s.value);
        expect(compiled.value(s.frame), at).toBe(s.value);
        expect(getInt(c.keyframe, s.frame), at).toBe(s.int);
        expect(getLong(c.keyframe, s.frame), at).toBe(s.long);
        expect(getDelta(c.keyframe, s.frame), at).toBe(s.delta);
        expect(isIncreasing(c.keyframe, s.frame), at).toBe(s.increasing);
      }
    });

    it(`${c.name}: loads the same points (sorted, deduplicated, defaults)`, () => {
      const ours = { Points: resolvePoints(c.keyframe).map(pointToJson) };
      expect(ours).toEqual(c.normalized);
    });
  }

  it("constructors write the same JSON", () => {
    const k = fixture.constructors;
    expect(openshotKeyframe(0.1)).toEqual(k["Keyframe(0.1)"]);
    expect(openshotPoint(30.97, 0.3, Interpolation.BEZIER)).toEqual(k["Point(30.97, 0.3, BEZIER)"]);
    expect(openshotPoint(5, 2, Interpolation.LINEAR)).toEqual(k["Point(5, 2, LINEAR)"]);
    expect(constantColor([0, 123, 255, 255])).toEqual(k["Color(0,123,255,255)"]);
  });

  it("color keyframes sample like Color::GetColorRGBA / GetColorHex", () => {
    const color = fixture.color.color as unknown as ColorKeyframe;
    for (const s of fixture.color.samples) {
      expect(evaluateColor(color, s.frame), `frame ${s.frame}`).toEqual(s.rgba);
      expect(colorHexAt(color, s.frame), `frame ${s.frame}`).toBe(s.hex);
    }
  });
});
