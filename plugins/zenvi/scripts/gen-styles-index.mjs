#!/usr/bin/env node
/**
 * The zenvi-styles index: one line per style and per technique, generated
 * from the YAML front matter of every file in skills/zenvi-styles/styles,
 * techniques and families, plus the motion director's genre recipes (the
 * first styles), into the marked table of skills/zenvi-styles/SKILL.md. An
 * agent reads this one short index, never hundreds of descriptions.
 *
 * Also writes packages/engine/src/styles/library.gen.ts (the index, BRIEF.md
 * and every file, for `zenvi mcp` and Zenvi Cloud to serve as zenvi://styles
 * resources from a single-file bundle).
 *
 *   node plugins/zenvi/scripts/gen-styles-index.mjs [--check]
 *
 * --check exits 1 when either output is stale or a front matter is invalid
 * (CI runs it through packages/cli/src/hosts/styles.test.ts).
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(here, "..", "..", "..");
const SKILLS = path.resolve(here, "..", "skills");
const STYLES = path.join(SKILLS, "zenvi-styles");
const RECIPES = path.join(SKILLS, "zenvi-motion-director", "recipes");
const LIBRARY_TARGET = path.join(ROOT, "packages", "engine", "src", "styles", "library.gen.ts");

export const START = "<!-- styles-index:start (generated by plugins/zenvi/scripts/gen-styles-index.mjs from front matter: do not edit) -->";
export const END = "<!-- styles-index:end -->";

const KINDS = new Set(["style", "technique"]);
const PACES = new Set(["calm", "medium", "fast", "frantic"]);
const LISTS = ["categories", "tools", "mood", "aspect", "pairs_with", "avoid_with", "needs"];
const MAX_SUMMARY = 120;
/** Ids MCP resources reserve next to the files' own. */
const RESERVED = new Set(["brief", "index"]);

/** `a, b` or `[a, b]` as a list. */
function inlineList(text) {
  const body = text.trim().replace(/^\[/, "").replace(/\]$/, "").trim();
  return body ? body.split(",").map((v) => unquote(v.trim())).filter(Boolean) : [];
}

function unquote(text) {
  const t = text.trim();
  return (t.startsWith('"') && t.endsWith('"')) || (t.startsWith("'") && t.endsWith("'")) ? t.slice(1, -1) : t;
}

/**
 * The YAML subset the skills use: `key: value`, `key: [a, b]` and block
 * lists (`key:` then `- item` lines). Returns null without front matter.
 */
export function parseFrontMatter(markdown) {
  const m = /^---\n([\s\S]*?)\n---\n?/.exec(markdown);
  if (!m) return null;
  const out = {};
  let list = null;
  for (const raw of m[1].split("\n")) {
    if (!raw.trim() || raw.trim().startsWith("#")) continue;
    const item = /^\s+-\s+(.*)$/.exec(raw) ?? /^-\s+(.*)$/.exec(raw);
    if (item && list) {
      out[list].push(unquote(item[1]));
      continue;
    }
    const kv = /^([A-Za-z_][\w-]*):\s*(.*)$/.exec(raw);
    if (!kv) throw new Error(`cannot read front matter line: ${raw}`);
    const [, key, value] = kv;
    if (value === "") {
      out[key] = [];
      list = key;
    } else {
      out[key] = LISTS.includes(key) || value.startsWith("[") ? inlineList(value) : unquote(value);
      list = null;
    }
  }
  return { meta: out, body: markdown.slice(m[0].length) };
}

function markdownFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.endsWith(".md"))
    .sort()
    .map((name) => path.join(dir, name));
}

/** Every entry of the library: front matter checked, path relative to zenvi-styles. */
export function readLibrary(styles = STYLES, recipes = RECIPES) {
  const errors = [];
  const entries = [];
  const sources = [
    ...markdownFiles(recipes).map((file) => ({ file, origin: "recipe" })),
    ...markdownFiles(path.join(styles, "styles")).map((file) => ({ file, origin: "style" })),
    ...markdownFiles(path.join(styles, "techniques")).map((file) => ({ file, origin: "technique" })),
  ];
  for (const { file, origin } of sources) {
    const rel = path.relative(styles, file).split(path.sep).join("/");
    const markdown = readFileSync(file, "utf8");
    let parsed;
    try {
      parsed = parseFrontMatter(markdown);
    } catch (error) {
      errors.push(`${rel}: ${error.message}`);
      continue;
    }
    if (!parsed) {
      errors.push(`${rel}: no front matter`);
      continue;
    }
    const meta = parsed.meta;
    const problems = [];
    if (!meta.id || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(meta.id)) problems.push("id must be kebab-case");
    else if (path.basename(file, ".md") !== meta.id) problems.push(`id ${meta.id} must match the file name`);
    if (!KINDS.has(meta.kind)) problems.push("kind must be style or technique");
    else if (origin !== "recipe" && meta.kind !== origin) problems.push(`a file in ${origin}s/ must be kind ${origin}`);
    if (typeof meta.summary !== "string" || !meta.summary) problems.push("summary is required");
    else if (meta.summary.length > MAX_SUMMARY) problems.push(`summary is ${meta.summary.length} characters (at most ${MAX_SUMMARY})`);
    if (!PACES.has(meta.pace)) problems.push("pace must be calm, medium, fast or frantic");
    for (const key of LISTS) if (meta[key] !== undefined && !Array.isArray(meta[key])) problems.push(`${key} must be a list`);
    if (RESERVED.has(meta.id)) problems.push(`id ${meta.id} is reserved`);
    if (problems.length > 0) {
      errors.push(`${rel}: ${problems.join("; ")}`);
      continue;
    }
    entries.push({
      id: meta.id,
      kind: meta.kind,
      summary: meta.summary,
      pace: meta.pace,
      tools: meta.tools ?? [],
      aspect: meta.aspect ?? [],
      categories: meta.categories ?? [],
      needs: meta.needs ?? [],
      // A drawn library's techniques (drawn: cinetic) are handed out by the brief's draw, not picked from the table.
      drawn: typeof meta.drawn === "string" ? meta.drawn : null,
      path: rel,
      markdown,
    });
  }
  const seen = new Map();
  for (const e of entries) {
    if (seen.has(e.id)) errors.push(`${e.path}: id ${e.id} is also ${seen.get(e.id)}`);
    else seen.set(e.id, e.path);
  }
  const families = markdownFiles(path.join(styles, "families")).map((file) => ({
    id: path.basename(file, ".md"),
    path: path.relative(styles, file).split(path.sep).join("/"),
    markdown: readFileSync(file, "utf8"),
  }));
  for (const f of families) {
    if (RESERVED.has(f.id)) errors.push(`${f.path}: id ${f.id} is reserved`);
    else if (seen.has(f.id)) errors.push(`${f.path}: id ${f.id} is also ${seen.get(f.id)}`);
    else seen.set(f.id, f.path);
  }
  // Methods (METHOD-<name>.md: how to plan, not a look) are served as zenvi://styles/method-<name>.
  const methods = existsSync(styles)
    ? readdirSync(styles)
        .filter((name) => /^METHOD-[A-Za-z0-9-]+\.md$/.test(name))
        .sort()
        .map((name) => ({ id: name.slice(0, -3).toLowerCase(), path: name, markdown: readFileSync(path.join(styles, name), "utf8") }))
    : [];
  for (const m of methods) if (seen.has(m.id)) errors.push(`${m.path}: id ${m.id} is also ${seen.get(m.id)}`);
  return { entries, families, methods, errors };
}

function cell(text) {
  return String(text).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
}

/** The generated block: a table of styles, a table of techniques, the families. */
export function indexTable({ entries, families, methods = [] }) {
  const styles = entries.filter((e) => e.kind === "style").sort((a, b) => a.id.localeCompare(b.id));
  const techniques = entries.filter((e) => e.kind === "technique" && !e.drawn).sort((a, b) => a.id.localeCompare(b.id));
  const drawn = new Map();
  for (const e of entries) if (e.kind === "technique" && e.drawn) drawn.set(e.drawn, (drawn.get(e.drawn) ?? 0) + 1);
  const lines = [START, "", `### Styles (${styles.length})`, "", "| style | pace | aspect | use when |", "| --- | --- | --- | --- |"];
  for (const s of styles) lines.push(`| [${s.id}](${s.path}) | ${s.pace} | ${cell(s.aspect.join(" ") || "any")} | ${cell(s.summary)} |`);
  lines.push("", `### Techniques (${techniques.length})`, "");
  if (techniques.length === 0) lines.push("None yet.");
  else {
    lines.push("| technique | pace | tools | use when |", "| --- | --- | --- | --- |");
    for (const t of techniques) {
      const needs = t.needs.length > 0 ? ` (needs ${t.needs.join(", ")})` : "";
      lines.push(`| [${t.id}](${t.path}) | ${t.pace} | ${cell(t.tools.join(" "))} | ${cell(t.summary + needs)} |`);
    }
  }
  if (drawn.size > 0) {
    lines.push("", "### Drawn libraries", "");
    for (const [library, count] of [...drawn].sort()) {
      lines.push(`- ${library}: ${count} techniques (front matter \`drawn: ${library}\`), never picked from a table: the brief of a ${library}-* style draws them (its \`draw\`; get_brief_tool, produce_video_tool) and get_technique_tool reads each.`);
    }
  }
  if (families.length > 0) {
    lines.push("", "### Families", "", ...families.map((f) => `- [${f.id}](${f.path})`));
  }
  if (methods.length > 0) {
    lines.push("", "### Methods", "", ...methods.map((m) => `- [${m.id}](${m.path})`));
  }
  lines.push("", END);
  return lines.join("\n");
}

/** SKILL.md with its marked block replaced. */
export function withIndex(skill, table) {
  const from = skill.indexOf(START);
  const to = skill.indexOf(END);
  if (from < 0 || to < from) throw new Error("zenvi-styles/SKILL.md has no styles-index markers");
  return skill.slice(0, from) + table + skill.slice(to + END.length);
}

function stripFrontMatter(markdown) {
  return markdown.replace(/^---\n[\s\S]*?\n---\n+/, "");
}

/** The index as MCP serves it: its links point at zenvi://styles/<id>, which a client can read, not at plugin paths. */
function withResourceLinks(skill, files) {
  let out = skill.replaceAll("](BRIEF.md)", "](zenvi://styles/brief)");
  for (const f of files) out = out.replaceAll(`](${f.path})`, `](zenvi://styles/${f.id})`);
  return out;
}

/** library.gen.ts: what the MCP servers serve as zenvi://styles resources. */
export function libraryModule(skill, brief, { entries, families, methods = [] }) {
  const files = [
    ...entries.map((e) => ({ id: e.id, kind: e.kind, path: e.path, summary: e.summary, markdown: e.markdown })),
    ...families.map((f) => ({ id: f.id, kind: "family", path: f.path, summary: `How the ${f.id} techniques combine.`, markdown: f.markdown })),
    ...methods.map((m) => ({ id: m.id, kind: "method", path: m.path, summary: `How to plan with the ${m.id.slice("method-".length)} method.`, markdown: m.markdown })),
  ];
  return [
    "// Generated from plugins/zenvi/skills/zenvi-styles by plugins/zenvi/scripts/gen-styles-index.mjs. Do not edit.",
    "",
    "/** zenvi-styles SKILL.md without its front matter: the one index (zenvi://styles). */",
    `export const STYLES_INDEX: string = ${JSON.stringify(withResourceLinks(stripFrontMatter(skill), files))};`,
    "",
    "/** BRIEF.md: the brief compiler, step 0 of every edit (zenvi://styles/brief). */",
    `export const STYLES_BRIEF: string = ${JSON.stringify(stripFrontMatter(brief))};`,
    "",
    "/** Every style, technique, family and method (zenvi://styles/<id>), by id. */",
    `export const STYLE_FILES: readonly { id: string; kind: "style" | "technique" | "family" | "method"; path: string; summary: string; markdown: string }[] = ${JSON.stringify(files, null, 2)};`,
    "",
  ].join("\n");
}

/** Both outputs from the files on disk. */
export function generate(styles = STYLES, recipes = RECIPES) {
  const library = readLibrary(styles, recipes);
  const skill = withIndex(readFileSync(path.join(styles, "SKILL.md"), "utf8"), indexTable(library));
  const brief = readFileSync(path.join(styles, "BRIEF.md"), "utf8");
  return { errors: library.errors, skill, module: libraryModule(skill, brief, library) };
}

function sync(target, text, check) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  const rel = path.relative(process.cwd(), target);
  if (current === text) return console.log(`${rel} is up to date`);
  if (check) {
    console.error(`${rel} is stale: run node plugins/zenvi/scripts/gen-styles-index.mjs`);
    process.exitCode = 1;
    return;
  }
  writeFileSync(target, text);
  console.log(`wrote ${rel}`);
}

if (path.resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const out = generate();
  for (const error of out.errors) console.error(`error: ${error}`);
  // A file with bad front matter is left out of the outputs: keep the last good ones rather than write a shorter index.
  if (out.errors.length > 0) process.exitCode = 1;
  else {
    sync(path.join(STYLES, "SKILL.md"), out.skill, check);
    sync(LIBRARY_TARGET, out.module, check);
  }
}
